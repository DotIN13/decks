import { CALLS, EVENTS, namesIn, type AnyCall, type Node } from "../../protocol/index.ts";

// The SDK's types and its list of calls, printed from the declarations.

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (name: string) => (IDENT.test(name) ? name : JSON.stringify(name));
const wrap = (text: string) => (text.includes(" | ") && !text.startsWith("{") ? `(${text})` : text);

/** The TypeScript for a node; a named node prints as its name unless expand is set. */
export function tsOf(node: Node, expand = false): string {
	if (node.name && !expand) return node.name;
	switch (node.k) {
		case "any":
			return "unknown";
		case "str":
			return "string";
		case "num":
			return "number";
		case "bool":
			return "boolean";
		case "null":
			return "null";
		case "lit":
			return node.values.map((v) => JSON.stringify(v)).join(" | ");
		case "arr":
			return `${wrap(tsOf(node.items))}[]`;
		case "union":
			return node.of.map((one) => wrap(tsOf(one))).join(" | ");
		case "obj":
			return objectTs(node);
	}
}

function objectTs(node: Extract<Node, { k: "obj" }>): string {
	const fields = Object.entries(node.props).map(([name, one]) => `${key(name)}${node.required.includes(name) ? "" : "?"}: ${tsOf(one)}`);
	const rest = node.rest === undefined ? undefined : node.rest === true ? "unknown" : tsOf(node.rest);
	if (rest && fields.length === 0) return `Record<string, ${rest}>`;
	if (rest) fields.push(`[key: string]: unknown`);
	return fields.length ? `{ ${fields.join("; ")} }` : "Record<string, never>";
}

/** Every named shape the calls and events use, in the order first met. */
export function namedShapes(): Map<string, Node> {
	const into = new Map<string, Node>();
	for (const call of CALLS) {
		namesIn(call.input, into);
		namesIn(call.answer, into);
	}
	for (const event of EVENTS) namesIn(event.payload, into);
	return into;
}

const doc = (text: string | undefined, indent = "") => (text ? `${indent}/** ${text.replace(/\*\//g, "* /")} */\n` : "");

function callEntry(call: AnyCall): string {
	return `${doc(call.summary, "\t")}\t${JSON.stringify(call.name)}: { args: ${tsOf(call.input)}; answer: ${tsOf(call.answer)} };`;
}

/** dist-gen/sdk/types.ts: the shapes, the calls and the events, as types. */
export function sdkTypes(version: string): string {
	const out = [`// Generated by tools/gen from protocol/ ${version}. Do not edit.`, ""];
	for (const [name, node] of namedShapes()) out.push(`${doc(node.doc)}export type ${name} = ${tsOf(node, true)};`);
	out.push("", "export interface Calls {", ...CALLS.map(callEntry), "}", "");
	out.push("export interface Events {", ...EVENTS.map((e) => `${doc(e.summary, "\t")}\t${JSON.stringify(e.name)}: ${tsOf(e.payload)};`), "}", "");
	out.push("export type CallName = keyof Calls;", "export type EventName = keyof Events;", "");
	return out.join("\n");
}

/** dist-gen/sdk/calls.json: each call's name, who may call it, where it is answered, and what it does. */
export function sdkCallList(): string {
	const list = CALLS.map((c) => ({ name: c.name, who: c.who, side: c.side, effect: c.effect, summary: c.summary, args: Object.keys(c.args) }));
	return `${JSON.stringify(list, null, "\t")}\n`;
}
