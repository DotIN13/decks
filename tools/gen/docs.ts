import { byNoun, nouns, type AnyCall, type Node, type Noun } from "../../protocol/index.ts";
import { tsOf } from "./ts.ts";

// The decks command's help, and the agents' command reference in markdown.
// A required string or number argument is a word; every other is a flag.

/** dist-gen/cli/help.txt: every call the decks command makes, by noun. */
export function cliHelp(version: string): string {
	const out = [`decks: every call of protocol ${version}, by noun. decks help <noun.verb> explains one.`, ""];
	for (const [noun, mod] of Object.entries(byNoun)) {
		const shown = calls(mod).filter((c) => c.side === "server");
		if (!shown.length) continue;
		out.push(`${noun}: ${nouns[noun as Noun]}`);
		for (const call of shown) out.push(`  ${usage(call)}`, `      ${call.summary}`);
		out.push("");
	}
	return out.join("\n");
}

/** dist-gen/reference.md: what an agent is told about every call it may make. */
export function reference(version: string): string {
	const out = [`# The decks calls (protocol ${version})`, "", "Generated by tools/gen from protocol/. Every call answers `{ ok, value, notes }` or a refusal `{ code, message, hint }`.", ""];
	for (const [noun, mod] of Object.entries(byNoun)) {
		const shown = calls(mod).filter((c) => c.side === "server" && c.who.includes("agent"));
		if (!shown.length) continue;
		out.push(`## ${noun}`, "", nouns[noun as Noun], "");
		for (const call of shown) {
			const args = Object.keys(call.args).length ? `args: ${tsOf(call.input)}` : "";
			out.push(`- \`${call.name}(${args})\` → \`${tsOf(call.answer)}\``);
			out.push(`  ${call.summary} *Who:* ${whoText(call)}.`);
		}
		out.push("");
	}
	return out.join("\n");
}

function usage(call: AnyCall): string {
	const input = call.input as Extract<Node, { k: "obj" }>;
	const parts = [`decks ${call.name.replace(".", " ")}`];
	for (const [name, node] of Object.entries(input.props)) {
		const needed = input.required.includes(name);
		if (needed && isWord(node)) parts.push(`<${name}>`);
		else parts.push(needed ? `--${name} <${tsOf(node)}>` : `[--${name} <${tsOf(node)}>]`);
	}
	return parts.join(" ");
}

const isWord = (node: Node) => node.k === "str" || node.k === "num";
const whoText = (call: AnyCall) => (call.who.length === 4 ? "anyone" : call.who.join(", "));
const calls = (mod: object) => Object.values(mod) as AnyCall[];
