// Writes cpp/bidi-data.h from Unicode 15.1's DerivedBidiClass.txt: each code point's bidirectional
// class, as sorted ranges, for the reordering of right-to-left text (`cpp/bidi.cpp`, UAX #9).
// Unlisted code points take the file's own `@missing` defaults (R for Hebrew's blocks, AL for
// Arabic's, and so on), then L.
// node packages/engine/tools/gen-bidi.mjs [folder with DerivedBidiClass.txt]
import { readFileSync, writeFileSync } from "node:fs";
const dir = process.argv[2] ?? "/mnt/data/decks-data/tools/unicode-15.1";
const MAX = 0x110000;
const CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"];
const cls = new Uint8Array(MAX).fill(0);
const text = readFileSync(`${dir}/DerivedBidiClass.txt`, "utf8");
const set = (range, value) => {
	const [a, b] = range.split("..").map((h) => parseInt(h, 16));
	const k = CLASSES.indexOf(value);
	if (k < 0) throw new Error(`unknown class ${value}`);
	for (let c = a; c <= (b ?? a); c++) cls[c] = k;
};
// The defaults first, in the file's order, then every listed code point over them.
for (const line of text.split("\n")) {
	const m = line.match(/^#\s*@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)/);
	if (m) set(m[1], m[2] === "Left_To_Right" ? "L" : m[2] === "Right_To_Left" ? "R" : m[2] === "Arabic_Letter" ? "AL" : m[2] === "European_Terminator" ? "ET" : m[2] === "Boundary_Neutral" ? "BN" : m[2]);
}
for (const line of text.split("\n")) {
	const body = line.split("#")[0].trim();
	if (!body) continue;
	const [range, value] = body.split(";").map((s) => s.trim());
	set(range, value);
}
const ranges = [];
for (let c = 0; c < MAX; ) {
	let e = c;
	while (e + 1 < MAX && cls[e + 1] === cls[c]) e++;
	if (cls[c] !== 0) ranges.push([c, e, cls[c]]);
	c = e + 1;
}
writeFileSync(
	new URL("../cpp/bidi-data.h", import.meta.url),
	`// Generated by tools/gen-bidi.mjs from Unicode 15.1's DerivedBidiClass.txt: do not edit by hand.\n` +
		`// Each range's first and last code point and its bidirectional class; anything not here is L.\n#pragma once\n#include <cstdint>\n\n` +
		`enum BidiClass : uint8_t { ${CLASSES.map((c) => `B_${c}`).join(", ")} };\n\n` +
		`struct BidiRange { uint32_t first, last; uint8_t cls; };\n` +
		`static const BidiRange BIDI_RANGES[] = {\n${ranges.map(([a, b, k]) => `\t{0x${a.toString(16)}, 0x${b.toString(16)}, ${k}},`).join("\n")}\n};\n`,
);
console.log(`${ranges.length} ranges`);
