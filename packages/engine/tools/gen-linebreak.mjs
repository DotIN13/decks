// Writes cpp/linebreak-data.h from Unicode 15.1's own files: each code point's line-break class
// (resolved as UAX #14's rule LB1 says), and the four properties the rules ask about beside it.
// node packages/engine/tools/gen-linebreak.mjs [folder with LineBreak.txt, EastAsianWidth.txt,
// DerivedGeneralCategory.txt, emoji-data.txt]
import { readFileSync, writeFileSync } from "node:fs";
const dir = process.argv[2] ?? "/mnt/data/decks-data/tools/unicode-15.1";
const MAX = 0x110000;
const read = (file, take) => {
	for (const line of readFileSync(`${dir}/${file}`, "utf8").split("\n")) {
		const body = line.split("#")[0].trim();
		if (!body) continue;
		const [range, value] = body.split(";").map((s) => s.trim());
		const [a, b] = range.split("..").map((h) => parseInt(h, 16));
		take(a, b ?? a, value);
	}
};
const CLASSES = ["AL", "SP", "GL", "ZW", "WJ", "OP", "CL", "CP", "QU", "NS", "EX", "SY", "IS", "PR", "PO", "NU", "HY", "BA", "BB", "B2", "ID", "CM", "ZWJ", "CB", "IN", "HL", "JL", "JV", "JT", "H2", "H3", "RI", "EB", "EM", "BK", "CR", "LF", "NL", "AK", "AP", "AS", "VI", "VF"];
const cls = new Uint8Array(MAX).fill(255);
const gc = new Array(MAX);
const ea = new Uint8Array(MAX);
const pict = new Uint8Array(MAX);
read("DerivedGeneralCategory.txt", (a, b, v) => { for (let c = a; c <= b; c++) gc[c] = v; });
read("EastAsianWidth.txt", (a, b, v) => { if (v === "F" || v === "W" || v === "H") for (let c = a; c <= b; c++) ea[c] = 1; });
read("emoji-data.txt", (a, b, v) => { if (v === "Extended_Pictographic") for (let c = a; c <= b; c++) pict[c] = 1; });
read("LineBreak.txt", (a, b, v) => {
	for (let c = a; c <= b; c++) {
		let k = v;
		// LB1: ambiguous, surrogates and unknown are letters; South-East Asian marks are marks; CJ is NS.
		if (k === "AI" || k === "SG" || k === "XX") k = "AL";
		else if (k === "SA") k = gc[c] === "Mn" || gc[c] === "Mc" ? "CM" : "AL";
		else if (k === "CJ") k = "NS";
		const i = CLASSES.indexOf(k);
		if (i < 0) throw new Error(`class ${k}`);
		cls[c] = i;
	}
});
// Unlisted code points are XX, which LB1 makes AL.
for (let c = 0; c < MAX; c++) if (cls[c] === 255) cls[c] = 0;
// Flags: 1 East Asian (F, W, H), 2 initial punctuation (Pi), 4 final punctuation (Pf), 8 Extended_Pictographic, 16 unassigned (Cn).
const flag = (c) => ea[c] | (gc[c] === "Pi" ? 2 : 0) | (gc[c] === "Pf" ? 4 : 0) | (pict[c] ? 8 : 0) | (gc[c] === undefined || gc[c] === "Cn" ? 16 : 0);
const ranges = [];
let start = 0;
for (let c = 1; c <= MAX; c++) {
	if (c === MAX || cls[c] !== cls[start] || flag(c) !== flag(start)) {
		ranges.push([start, c - 1, cls[start], flag(start)]);
		start = c;
	}
}
const rows = ranges.map(([a, b, k, f]) => `{0x${a.toString(16)},0x${b.toString(16)},${k},${f}}`);
const out = `// Generated by tools/gen-linebreak.mjs from Unicode 15.1.0 (LineBreak.txt, EastAsianWidth.txt,
// DerivedGeneralCategory.txt, emoji-data.txt). Do not edit: run the script again.
#pragma once
#include <cstdint>
namespace linebreak {
enum Cls : uint8_t { ${CLASSES.join(", ")} };
enum Flag : uint8_t { EAST_ASIAN = 1, PI = 2, PF = 4, PICTOGRAPHIC = 8, UNASSIGNED = 16 };
struct Range { uint32_t from, to; uint8_t cls, flags; };
constexpr int RANGES = ${ranges.length};
static const Range table[RANGES] = {
${rows.join(",")}
};
}  // namespace linebreak
`;
writeFileSync(new URL("../cpp/linebreak-data.h", import.meta.url), out);
console.log(`${ranges.length} ranges written`);
